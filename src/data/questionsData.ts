export function getQuestionById(id: string): LearningQuestion | undefined {
  return ALL_LEARNING_QUESTIONS.find((q) => q.id === id);
}

export function getQuestionsByUnit(unitId: string): LearningQuestion[] {
  return ALL_LEARNING_QUESTIONS.filter((q) => q.unitId === unitId);
}

export function getQuestionsBySkill(skillId: string): LearningQuestion[] {
  return ALL_LEARNING_QUESTIONS.filter((q) => q.skillId === skillId);
}

export function getPrerequisiteQuestions(prerequisiteId: string, limit = 3): LearningQuestion[] {
  // First try by skillId
  let found = ALL_LEARNING_QUESTIONS.filter((q) => q.skillId === prerequisiteId);
  if (found.length > 0) return found.slice(0, limit);

  // Second try by unitId
  found = ALL_LEARNING_QUESTIONS.filter((q) => q.unitId === prerequisiteId);
  if (found.length > 0) return found.slice(0, limit);

  // Fallback: Return Grade 2-4 questions
  return ALL_LEARNING_QUESTIONS.filter((q) => q.grade <= 4).slice(0, limit);
}
